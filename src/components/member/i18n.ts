/** Texte traduit (retombe sur le français) ; variables « {n} » */
export function mt(lang: Lang, key: MKey, vars?: Record<string, string | number>) {
  let s: string = (lang === "ar" ? ar[key] : undefined) ?? fr[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Date au format de la langue (fuseau d'Agadir) */
export function mDate(lang: Lang, d: string | Date, opts: Intl.DateTimeFormatOptions = { day: "numeric", month: "short", year: "numeric" }) {
  const date = typeof d === "string" && /^\d{4}-\d{2}-\d{2}$/.test(d) ? new Date(`${d}T12:00:00Z`) : new Date(d);
  return new Intl.DateTimeFormat(lang === "ar" ? "ar-MA" : "fr-FR", { timeZone: "Africa/Casablanca", ...opts }).format(date);
}

/** Heure « 14:30 » (fuseau d'Agadir) */
export function mTime(d: string | Date) {
  return new Intl.DateTimeFormat("fr-FR", { hour: "2-digit", minute: "2-digit", timeZone: "Africa/Casablanca" }).format(new Date(d));
}
